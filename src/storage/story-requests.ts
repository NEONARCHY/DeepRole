import { assertStoryGraph, assertStoryRequestLinks, storyRow, validStoryRecord, validStoryRequestDelivery, type StoryBaseline, type StoryBranch, type StoryProjection, type StoryRecord, type StoryRequest } from "../core/story-records";
import { sameStoryValue } from "../core/story-value";
import { projectStoryBranch } from "../core/story-projection";
import { projectStoryRequestContext, type StoryRequestContextValue } from "../core/story-request-context";
import { validStoryTransportIdentity, type StoryTransportIdentity } from "../core/story-transport";
import type { ChatBinding, DataRecord } from "../core/types";
import { repository, type DeepRoleRepository } from "./repository";
import { recordStoryObservation, type StoryObservation } from "./story-history";
import { storySceneOwner } from "./story-scene-owner";

export interface StoryRequestPreparation {
  /** Locally assigned before network delivery, not echoed/generated by the model. */
  id: string;
  purpose: StoryRequest["purpose"];
  bindingId: string;
  identity: StoryTransportIdentity;
  parentRevisionId: string | null;
  expectedHeadRevisionId: string | null;
  expectedSelectionVersion: number;
  expectedSceneRevision: string | null;
}
export type StoryRequestSettlement = { status: "accepted"; httpStatus: number }
  | { status: "failed"; reason: "network" | "aborted" | "http"; httpStatus: number | null };

/** Internal local API. Does not send a request, select a branch, or apply game effects. */
export async function prepareStoryRequest(branchId: string, input: StoryRequestPreparation, repo: DeepRoleRepository = repository): Promise<StoryRequest> {
  input = structuredClone(input);
  if (!validStoryTransportIdentity(input.identity) || !Number.isSafeInteger(input.expectedSelectionVersion) || input.expectedSelectionVersion < 0) throw new Error("story-request-invalid");
  return repo.updateRecords(all => {
    return planStoryRequest(all, branchId, input);
  }, undefined, ["story", "world", "binding"]);
}

/** Pure planner for an atomic outgoing capture + pre-send receipt. Caller owns the lock. */
export function planStoryRequest(all: DataRecord[], branchId: string, input: StoryRequestPreparation) {
    input = structuredClone(input);
    if (!validStoryTransportIdentity(input.identity) || !Number.isSafeInteger(input.expectedSelectionVersion) || input.expectedSelectionVersion < 0) throw new Error("story-request-invalid");
    assertStoryGraph(all);
    const stored = new Map(all.filter(row => row.kind === "story").map(row => [row.id, row.data as StoryRecord]));
    const branch = stored.get(branchId);
    if (branch?.type !== "branch" || branch.worldId === null) throw new Error("story-scope-invalid");
    if (branch.parentBranchId !== null) throw new Error("story-branch-routing-required");
    const now = Date.now();
    const request: StoryRequest = { format: "deeprole-story", contractVersion: 1, type: "request", id: input.id, branchId, worldId: branch.worldId, playthroughId: branch.playthroughId,
      purpose: input.purpose, bindingId: input.bindingId, chatId: input.identity.chatId, nativeParentKey: input.identity.nativeParentKey, parentRevisionId: input.parentRevisionId,
      selectedHeadRevisionId: input.expectedHeadRevisionId, selectionVersion: input.expectedSelectionVersion, sceneRevision: input.expectedSceneRevision, delivery: { status: "prepared" }, createdAt: now, updatedAt: now };
    if (!validStoryRecord(request)) throw new Error("story-request-invalid");
    const previous = stored.get(input.id);
    if (previous) {
      const immutable = ({ delivery: _delivery, context: _context, createdAt: _created, updatedAt: _updated, ...route }: StoryRequest) => route;
      if (previous.type !== "request" || !sameStoryValue(immutable(previous), immutable(request))) throw new Error("story-request-conflict");
      // An idempotent retry cannot overwrite a newer branch choice or manual edit.
      return { records: [], removed: [], result: structuredClone(previous) };
    }
    if (branch.headRevisionId !== input.expectedHeadRevisionId || branch.selectionVersion !== input.expectedSelectionVersion) throw new Error("story-selection-conflict");
    if (!branch.projectionId && (branch.headRevisionId !== null || branch.selectionVersion !== 0)) throw new Error("story-projection-missing");
    assertStoryRequestLinks(request, branch, stored);
    const baseline = stored.get(branch.baselineId) as StoryBaseline, projection = stored.get(branch.projectionId ?? "") as StoryProjection | undefined;
    const binding = all.find(row => row.kind === "binding" && row.id === input.bindingId)?.data as ChatBinding | undefined;
    if (!binding || binding.chatId !== request.chatId || binding.worldId !== branch.worldId) throw new Error("story-binding-conflict");
    storySceneOwner(all, binding, branch.worldId, branch.id);
    const scene = binding.characterScenes?.[branch.worldId], expected = projection?.snapshot ?? baseline.snapshot;
    const sceneValue = { states: scene?.states ?? {}, presentIds: scene?.presentIds ?? [], partnerIds: scene?.partnerIds ?? (scene?.partnerId ? [scene.partnerId] : []) };
    if ((scene?.revision ?? null) !== input.expectedSceneRevision || input.expectedSceneRevision !== (projection?.bindingRevision ?? baseline.origin.sceneRevision) || !sameStoryValue(sceneValue, { states: expected.states, presentIds: expected.presentIds, partnerIds: expected.partnerIds })) throw new Error("story-manual-conflict");
    const parentContext = projectStoryBranch([...stored.values()], branchId, request.parentRevisionId, projection?.acceptedEventIds ?? []);
    request.context = { algorithmVersion: 1, acceptedEventIds: [...parentContext.appliedEventIds].sort() };
    const row = storyRow(request); assertStoryGraph([...all, row]);
    return { records: [row], removed: [], result: structuredClone(request) };
}

/** Read-only, branch-scoped receipt reference; not authorization to send a stale request.
 * Includes archived requests for history/debugging. The game sender still needs live route guards.
 */
export async function readStoryRequestContext(branchId: string, requestId: string, repo: DeepRoleRepository = repository): Promise<StoryRequestContextValue> {
  return repo.updateRecords(all => {
    assertStoryGraph(all);
    const records = all.filter(row => row.kind === "story").map(row => row.data as StoryRecord);
    return { records: [], removed: [], result: projectStoryRequestContext(records, branchId, requestId) };
  }, undefined, ["story", "world"]);
}

/** HTTP success confirms delivery only. No stream consumption and no inferred completion. */
export async function settleStoryRequest(id: string, input: StoryRequestSettlement, repo: DeepRoleRepository = repository): Promise<StoryRequest> {
  input = structuredClone(input);
  if (!Object.keys(input).every(key => ["status", "httpStatus", "reason"].includes(key)) || !validStoryRequestDelivery({ ...input, at: Date.now() }) || input.status !== "accepted" && input.status !== "failed") throw new Error("story-request-invalid");
  return repo.updateRecords(all => {
    return planStoryRequestSettlement(all, id, input);
  }, undefined, ["story", "world"]);
}

/** Delivery and its dispatch journal advance together, never in two partial writes. */
export function planStoryRequestSettlement(all: DataRecord[], id: string, input: StoryRequestSettlement) {
    input = structuredClone(input);
    if (!Object.keys(input).every(key => ["status", "httpStatus", "reason"].includes(key)) || !validStoryRequestDelivery({ ...input, at: Date.now() }) || input.status !== "accepted" && input.status !== "failed") throw new Error("story-request-invalid");
    assertStoryGraph(all);
    const request = all.find(row => row.kind === "story" && row.id === id)?.data as StoryRecord | undefined;
    if (request?.type !== "request") throw new Error("story-request-missing");
    const branch = all.find(row => row.kind === "story" && row.id === request.branchId)?.data as StoryBranch;
    if (request.worldId === null || branch.parentBranchId !== null) throw new Error("story-scope-invalid");
    if (request.delivery.status !== "prepared") {
      const { at: _at, ...result } = request.delivery;
      if (!sameStoryValue(result, input)) throw new Error("story-request-settlement-conflict");
      return { records: [], removed: [], result: structuredClone(request) };
    }
    const now = Math.max(Date.now(), request.updatedAt), next: StoryRequest = { ...request, delivery: { ...input, at: now }, updatedAt: now };
    const row = storyRow(next); assertStoryGraph([...all.filter(old => old.id !== id || old.kind !== "story"), row]);
    return { records: [row], removed: [], result: structuredClone(next) };
}

/** The proof must come from an explicit native identity reader, not a model response.
 * recordStoryObservation checks the receipt and all links under its single write lock.
 */
export async function recordRequestedStoryObservation(branchId: string, input: StoryObservation, repo: DeepRoleRepository = repository): Promise<"recorded" | "already-recorded"> {
  input = structuredClone(input);
  if (!input.requestId || !input.requestProof) throw new Error("story-request-unproven");
  return recordStoryObservation(branchId, input, repo);
}
