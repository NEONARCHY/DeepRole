for (const locale of ["ru", "en"] as const) test(`an older fact keeps its source and stays outside current memory (${locale})`, async ({ page }) => {
  const t = (key: Parameters<typeof text>[1]) => text(locale, key);
  await page.setViewportSize({ width: 320, height: 420 });
  await page.emulateMedia({ colorScheme: locale === "ru" ? "dark" : "light" });
  await page.goto(`/tests/fixtures/story-memory-ui.html?older&locale=${locale}`);
  await page.addStyleTag({ content: "html { font-size: 125%; }" });
  await page.getByRole("button", { name: storyReviewText(locale, "read") }).click();
  const row = page.locator(".dr-fact-entry");
  await expect(row.getByText(t("supersededFact"), { exact: true })).toBeVisible();
  await row.getByRole("button", { name: t("excludeOlder") }).press("Enter");
  await expect(row.getByText(t("excludeOlderHint"), { exact: true })).toBeVisible();
  expect(await row.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
  await row.getByRole("button", { name: t("cancelDecision") }).press("Enter");
  await row.getByRole("button", { name: t("editText") }).press("Enter");
  await row.locator("summary").press("Enter");
  await expect(row.locator(".dr-story-review-source")).toHaveText("Lighthouse".repeat(20));
  expect(await page.evaluate(() => (window as any).storyMemoryFixture.calls)).toEqual([]);
});
