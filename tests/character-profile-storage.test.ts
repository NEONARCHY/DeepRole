import { afterEach, expect, it } from "vitest";
import { DeepRoleDatabase } from "../src/storage/database";
import { DeepRoleRepository } from "../src/storage/repository";
import { saveCharacter, applyCharacterTurn } from "../src/storage/characters";
import { characterEditBaseline } from "../src/core/character-edit";
import { characterInstruction, characterRevision, EMPTY_CHARACTER, EMPTY_STATUS } from "../src/core/characters";
import { injectIntoJsonBody } from "../src/core/request-injection";
import { isolatedFieldPrompt } from "../src/core/isolated-character-text";
import { characterTextRequest } from "../src/core/character-text";
import { profileField, profileValues } from "../src/core/character-profile";
import { castRecords, castBinding } from "./fixtures/cast-data";
import { DEFAULT_SETTINGS } from "../src/core/defaults";
import type { SceneEntity, ChatBinding } from "../src/core/types";
let database: DeepRoleDatabase | undefined;
afterEach(async () => { await database?.delete(); database = undefined; });
it("user-edited invented details become saved world facts in the next game request and survive later story updates", async () => {
 database = new DeepRoleDatabase("profile-canon-" + crypto.randomUUID()); const repo = new DeepRoleRepository(database); await repo.mergeRecords(castRecords());
 const sheet = { ...EMPTY_CHARACTER, appearance: "USER_CUSTOM green coat", personality: "USER_CUSTOM patient", goals: "USER_CUSTOM open a bakery", background: "Mira’s friend; USER_CUSTOM grew up by the harbor" };
 const before = await repo.rawRecords(), scope = { worldId: "w", chatId: "a", chatUrl: castBinding.chatUrl, base: characterRevision([]) };
 const saved = await saveCharacter({ ...scope, entityId: null, name: "Nora", sheet, state: EMPTY_STATUS, present: false, original: characterEditBaseline(null, []) }, repo);
 expect(await repo.get("world", "w")).toEqual(before.find(r => r.kind === "world")!.data);
 let person = (await repo.get<SceneEntity>("entity", saved.entityId))!; const scene = (await repo.get<ChatBinding>("binding", castBinding.id))!.characterScenes!.w!;
 expect(person.characterSheet).toEqual(sheet);
 const instruction = characterInstruction("w", "a", [person], scene, ["neutral"], [person.id], "Talk to Nora");
 for (const value of Object.values(profileValues(sheet))) expect(instruction).toContain(value);
 expect(instruction).toContain("Manual profile facts override older descriptions");
 const body = injectIntoJsonBody(JSON.stringify({messages:[{role:"user",content:"Talk to Nora"}]}), instruction);
 expect(body.changed).toBe(true);
 for (const value of Object.values(profileValues(sheet))) expect(JSON.parse(body.body).messages[0].content).toContain(value);
 await applyCharacterTurn({ ...scope, base: saved.base }, { world:"w",chat:"a",base:saved.base,present:[person.id],updates:[{id:person.id,appearance:"MODEL_REPLACEMENT",personality:"MODEL_REPLACEMENT",state:{...EMPTY_STATUS,condition:"At the gate"}}] }, ["neutral"], repo);
 person = (await repo.get<SceneEntity>("entity", person.id))!; expect(person.characterSheet).toEqual(sheet);
 const prompt = isolatedFieldPrompt({scope:{chatId:"a",chatUrl:castBinding.chatUrl,worldId:"w",bookId:null},locale:"en",draft:characterTextRequest(profileField("en","history"),JSON.stringify(profileValues(sheet)),person.name,person,sheet,EMPTY_STATUS),sceneReference:""},await repo.rawRecords(),DEFAULT_SETTINGS,"field_next").prompt;
 for (const value of Object.values(profileValues(sheet))) expect(prompt).toContain(value);
 expect(prompt).not.toContain("MODEL_REPLACEMENT");
});
