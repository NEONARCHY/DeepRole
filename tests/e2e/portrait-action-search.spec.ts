import { expect, test } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { characterTab } from "./character-helpers";
import { chooseImageCompression } from "./image-upload-helpers";

for(const locale of ["ru","en"] as const)for(const width of [320,1100])test(`image assignment search ${locale} ${width}`,async({page},info)=>{
  const l=(ru:string,en:string)=>locale==="ru"?ru:en;
  await page.setViewportSize({width,height:950});await page.goto(`/tests/fixtures/characters.html?locale=${locale}`);
  await page.locator(".dr-action-settings > .dr-action-help > summary").first().click();
  await page.getByLabel(l("Действия для портретов","Portrait actions"),{exact:true}).fill("neutral\nhappy\nsad\nСмеётся тихо\nОбнимает");
  await page.getByRole("button",{name:l("Сохранить действия","Save actions"),exact:true}).click();
  await page.locator(".dr-character-row").filter({hasText:"Mira"}).click();const dialog=page.getByRole("dialog");await characterTab(dialog,"images",locale);
  const library=dialog.locator(".dr-portrait-library");
  const png=await page.evaluate(()=>{const c=document.createElement("canvas");c.width=40;c.height=60;c.getContext("2d")!.fillRect(0,0,40,60);return c.toDataURL().split(",")[1]!;});
  await library.locator("input[type=file]").setInputFiles({name:"test.png",mimeType:"image/png",buffer:Buffer.from(png,"base64")});await chooseImageCompression(page);
  await expect(library.locator(".dr-library-image")).toHaveCount(1);
  await library.locator("select").selectOption("neutral");
  await library.locator(".dr-library-actions summary").click();
  const search=library.getByRole("searchbox",{name:l("Найти эмоцию или действие","Find an emotion or action")});
  await search.fill(locale==="ru"?"РАД":"HAP");
  await expect(library.getByRole("checkbox",{name:l("Радость","Happy"),exact:true})).toBeVisible();
  await expect(library.getByRole("checkbox",{name:l("Грусть","Sad"),exact:true})).toHaveCount(0);
  await library.getByRole("checkbox",{name:l("Радость","Happy"),exact:true}).check();
  await search.fill(" ТИХО  смеется ");await expect(library.getByRole("checkbox",{name:"Смеётся тихо",exact:true})).toBeVisible();
  await library.getByRole("checkbox",{name:"Смеётся тихо",exact:true}).check();
  await library.locator("select").selectOption("Смеётся тихо");
  await search.fill("Обни");await library.getByRole("checkbox",{name:"Обнимает",exact:true}).check();
  await search.fill("не существует");await expect(library.getByText(l("Ничего не найдено","No matches"),{exact:true})).toBeVisible();
  await expect(library.locator("select")).toHaveValue("Смеётся тихо");
  await expect(library.locator(".dr-library-targets")).toContainText(l("Радость","Happy"));await expect(library.locator(".dr-library-targets")).toContainText("Обнимает");
  await search.press("Enter");await expect(dialog.locator("footer [role=status]")).toHaveCount(0);expect(await page.evaluate(()=>(window as any).saved)).toBeUndefined();await expect(dialog).toBeVisible();
  expect(await library.evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true);
  expect((await new AxeBuilder({page}).include(".dr-portrait-library").withTags(["wcag2a","wcag2aa","wcag21aa"]).analyze()).violations).toEqual([]);
  if(info.project.name==="chromium")await page.screenshot({path:info.outputPath(`search-${locale}-${width}.png`)});
  await search.press("Escape");await expect(search).toHaveValue("");await expect(dialog).toBeVisible();
  await search.fill("обни");await library.getByRole("button",{name:l("Сбросить поиск эмоций","Clear emotion search")}).click();await expect(search).toBeFocused();await expect(search).toHaveValue("");
  await expect(library.getByRole("checkbox",{name:l("Радость","Happy"),exact:true})).toBeChecked();
  await library.getByRole("button",{name:l("Назначить действия","Assign to action"),exact:true}).click();
  await dialog.getByRole("button",{name:l("Сохранить персонажа","Save character"),exact:true}).click();
  await expect(dialog.locator("footer [role=status]")).toHaveText(l("Сохранено","Saved"));
  const saved=await page.evaluate(()=>(window as any).saved.sheet);
  expect(Object.keys(saved.sprites).sort()).toEqual(["happy","Смеётся тихо","Обнимает"].sort());
  expect(saved.sprites.happy).toEqual(saved.sprites["Смеётся тихо"]);expect(saved.sprites["Обнимает"]).toEqual(saved.sprites.happy);
  await search.fill("рад");await expect(dialog.locator(".dr-editor-unsaved")).toHaveCount(0);
  await expect(dialog.locator("footer [role=status]")).toHaveText(l("Сохранено","Saved"));
});
