import { discoveryName, type CharacterDiscoveryScope } from "../core/story-character-discovery";
import { validDiscoveryQueueInput, type DiscoveryQueueInput } from "../core/discovery-profile-queue";
import { sameStoryValue } from "../core/story-value";
import { storyRow, type StoryEvent } from "../core/story-records";
import { scopedDiscovery, discoveryGuard } from "./story-character-discovery";
import { repository, type DeepRoleRepository } from "./repository";

export async function editDiscoveryQueue(input: DiscoveryQueueInput, repo: DeepRoleRepository = repository, current?: () => Promise<void>) {
  input = structuredClone(input); if (!validDiscoveryQueueInput(input)) throw Error("story-review-invalid");
  await current?.();
  return repo.updateRecords(all => {
    const f = scopedDiscovery(all, input); discoveryGuard(f.guard, input.guard);
    const events = f.stored.filter((e): e is StoryEvent => e.type === "event" && !!e.characterCandidate && !e.characterCandidate.dismissed && !e.effects && f.selected.some(r => r.id === e.revisionId));
    const queued = events.filter(e => e.characterProfileTask);
    if (input.operation === "enqueue" && queued.some(e => e.characterProfileTask!.status === "preparing")) throw Error("busy");
    let changed: StoryEvent[];
    if (input.operation === "clear") {
      changed = queued.map(e => { const copy = { ...e }; delete copy.characterProfileTask; return copy; });
    } else if (input.operation === "resume") {
      const pending = queued.filter(e => e.characterProfileTask!.status !== "ready");
      if (pending.some(e => !sameStoryValue(e.characterProfileTask!.guard, f.guard))) throw Error("story-review-stale");
      changed = pending.map(e => ({ ...e, characterProfileTask: { ...e.characterProfileTask!, status: "pending", requestId: null } }));
    } else {
      const names = new Set<string>(), known = new Set(f.people.flatMap(p => [p.name, ...p.aliases].map(discoveryName)));
      changed = input.items.flatMap(i => {
        const event = events.find(e => e.id === i.eventId); if (!event || !f.branch.headRevisionId) throw Error("scene-changed");
        const n = discoveryName(i.name); if (known.has(n) || names.has(n) || events.some(e => e.id !== i.eventId && e.characterProfileTask?.status !== "ready" && e.characterProfileTask && discoveryName(e.characterProfileTask.name) === n)) throw Error("character-discovery-known"); names.add(n);
        // A completed proposal is never regenerated by a queue retry.
        if (event.characterProfile?.headRevisionId === f.guard.headRevisionId || event.characterProfileTask && sameStoryValue(event.characterProfileTask.guard, f.guard)) return [];
        return [{ ...event, characterProfileTask: { id: "profilequeue_" + crypto.randomUUID(), guard: f.guard, name: i.name, values: i.values, status: "pending" as const, requestId: null } }];
      });
    }
    return { records: changed.map(e => storyRow({ ...e, updatedAt: Date.now() })), removed: [], result: undefined };
  }, current);
}

/** Only reconcile after the coordinator has verified that no owned worker is active. */
export async function failDiscoveryProfileTask(scope: CharacterDiscoveryScope & { eventId: string; queueId?: string }, requestId: string, repo: DeepRoleRepository = repository) {
  if (!scope.queueId) return;
  await repo.updateRecords(all => {
    const row = all.find(r => r.kind === "story" && r.id === scope.eventId), event = row?.data as StoryEvent | undefined, task = event?.characterProfileTask;
    if (!event || event.worldId !== scope.worldId || !task || task.id !== scope.queueId || task.status !== "preparing" || task.requestId !== requestId) return { records: [], removed: [], result: undefined };
    return { records: [storyRow({ ...event, characterProfileTask: { ...task, status: "failed" }, updatedAt: Date.now() })], removed: [], result: undefined };
  }, undefined, ["story"]);
}
